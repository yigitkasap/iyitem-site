export type UIKey = keyof (typeof UI)['tr'];

/** Returns a translator for `locale`, falling back to Turkish for gaps. */
export function useTranslations(locale: Locale) {
  return function t(key: UIKey): string {
    const table = UI[locale] as Record<string, string>;
    return table[key] ?? (UI.tr as Record<string, string>)[key] ?? key;
  };
}
